"""Splits docs/aquaguard_asset_sheet.svg into isolated per-asset SVGs and builds the animated inline sources.

Run from the repo root:  python frontend/scripts/build-illustrations.py
Writes frontend/public/illustrations/svg/<id>.svg (static, one per asset, viewBox -150 -150 300 300 = one sheet cell)
and frontend/src/components/illustrations/animatedSources.ts (SMIL-animated markup for the layers that move).
The PNGs in frontend/public/illustrations/png come straight from docs/aquaguard_individual_pngs (never cropped from the sheet).
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHEET = ROOT / 'docs' / 'aquaguard_asset_sheet.svg'
SVG_DIR = ROOT / 'frontend' / 'public' / 'illustrations' / 'svg'
TS_OUT = ROOT / 'frontend' / 'src' / 'components' / 'illustrations' / 'animatedSources.ts'
HEAD = 'xmlns="http://www.w3.org/2000/svg" viewBox="-150 -150 300 300" stroke-linejoin="round" stroke-linecap="round"'

assets = {}
for line in SHEET.read_text(encoding='utf8').split('\n'):
    m = re.match(r'<g id="([a-z_0-9]+)" transform="translate\([\d.]+ [\d.]+\)">(.*)</g>$', line)
    if m: assets[m.group(1)] = m.group(2)
assert len(assets) == 37, len(assets)

SVG_DIR.mkdir(parents=True, exist_ok=True)
for k, inner in assets.items():
    (SVG_DIR / f'{k}.svg').write_text(f'<svg {HEAD} width="600" height="600">{inner}</svg>\n', encoding='utf8')

SPLINE = 'calcMode="spline" keyTimes="0;.5;1" keySplines=".45 0 .55 1;.45 0 .55 1"'
def anim_attr(name, values, dur, begin=0):
    return f'<animate attributeName="{name}" values="{values}" dur="{dur}s" begin="{begin}s" repeatCount="indefinite" {SPLINE}/>'
def anim_tf(kind, values, dur, extra=''):
    return f'<animateTransform attributeName="transform" type="{kind}" values="{values}" dur="{dur}s" repeatCount="indefinite" additive="sum" {SPLINE} {extra}/>'

def layer(markup):
    """Ids repeat across assets, so inline sources carry data-layer instead (still targetable, never colliding)."""
    return re.sub(r' id="([a-z_0-9]+)"', r' data-layer="\1"', markup)

def paddles(m):
    body, i = m.group(0), [0]
    def rect(r):
        y, h = float(r.group(2)), float(r.group(4)); b = i[0] * 0.28; i[0] += 1
        return (f'{r.group(1)}{r.group(2)}{r.group(3)}{r.group(4)}{r.group(5)}>'
                + anim_attr('height', f'{h:g};{h*.4:g};{h:g}', 1.4, b) + anim_attr('y', f'{y:g};{y+h*.3:g};{y:g}', 1.4, b) + '</rect>')
    return re.sub(r'(<rect x="-?[\d.]+" y=")(-?[\d.]+)(" width="10.0" height=")([\d.]+)(" rx="3" fill="#f08a3c"[^>]*?) ?/>', rect, body)

def aerator_on(s):
    s = re.sub(r'<g id="paddlewheel".*?(?=<g id="aerator_motor">)', paddles, s, flags=re.S)
    s = s.replace('<g id="aerator_splash">', '<g id="aerator_splash">' + anim_tf('translate', '0 0;0 -4;0 0', 1.8) + anim_attr('opacity', '1;.65;1', 1.8))
    return s

def flow(s, name):
    def one(m):
        g = m.group(0)
        return re.sub(r'(<path d="[^"]*" fill="none" stroke="#fff" stroke-width="4" stroke-opacity="\.9")/>',
                      r'\1 stroke-dasharray="46 10"><animate attributeName="stroke-dashoffset" from="0" to="-56" dur="1.1s" repeatCount="indefinite"/></path>', g)
    return re.sub(rf'<g id="{name}">.*?</g>', one, s, flags=re.S)

def tail(s, values, dur):
    return re.sub(r'(<g id="fish_tail"[^>]*>)(<path .*?/>)(</g>)',
                  lambda m: f'{m.group(1)}<g><animateTransform attributeName="transform" type="rotate" values="{values}" dur="{dur}s" repeatCount="indefinite" {SPLINE}/>{m.group(2)}</g>{m.group(3)}', s, count=1)

def farmer(s):
    s = s.replace('<g id="farmer_arms">', '<g id="farmer_arms">' + anim_tf('translate', '0 0;0 -3;0 0', 2.2))
    return re.sub(r'(<g id="sweat_drop" transform="[^"]*">)', r'\1<animateTransform attributeName="transform" type="translate" values="0 0;0 12;0 12" dur="2.4s" repeatCount="indefinite" additive="sum"/><animate attributeName="opacity" values="1;1;0" keyTimes="0;.6;1" dur="2.4s" repeatCount="indefinite"/>', s)

pipe_out = {k: flow(assets[k], k.replace('pipe', 'flow')) for k in ('inlet_pipe', 'outlet_pipe')}
sources = {
    'aerator_on': aerator_on(assets['aerator_on']),
    'inlet_pipe': pipe_out['inlet_pipe'], 'outlet_pipe': pipe_out['outlet_pipe'],
    'fish_normal': tail(assets['fish_normal'], '-9 -32 0;9 -32 0;-9 -32 0', 1.0),
    'fish_sluggish': tail(assets['fish_sluggish'], '-4 -32 0;4 -32 0;-4 -32 0', 2.6),
    'fish_gasping': tail(assets['fish_gasping'], '-6 -32 0;6 -32 0;-6 -32 0', 0.8),
    'fish_motionless': assets['fish_motionless'],  # deliberately still
    'farmer_concerned': farmer(assets['farmer_concerned']),
}
for k, v in sources.items():
    assert v == assets[k] or '<animate' in v, f'animation not applied to {k}'
for k in ('inlet_pipe', 'outlet_pipe'): assert 'stroke-dashoffset' in sources[k], k
assert sources['aerator_on'].count('attributeName="height"') == 5

TS_OUT.write_text('// GENERATED by frontend/scripts/build-illustrations.py from docs/aquaguard_asset_sheet.svg. Do not edit by hand.\n'
                  '// Inner SVG markup (viewBox -150 -150 300 300) with SMIL animation on the original layers. Layer ids are exposed as data-layer.\n'
                  f'export const ANIMATED_SOURCES = {json.dumps({k: layer(v) for k, v in sources.items()}, indent=1)} as const;\n'
                  'export type AnimatedSourceId = keyof typeof ANIMATED_SOURCES;\n', encoding='utf8')
print('ok', len(assets), 'svgs;', len(sources), 'animated sources')
